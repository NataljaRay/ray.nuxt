function byOrder(a, b) {
    return a.order - b.order
}

export function getMusicAlbums() {
    return musicItems
        .filter((item) => item.release)
        .map((item) => ({
            cover: item.cover,
            title: item.title,
            ...item.release,
        }))
        .sort(byOrder)
        .map(({ order, ...album }) => album)
}

export function getSoundtracks() {
    return musicItems
        .filter((item) => item.soundtrack)
        .map((item) => ({
            cover: item.cover,
            title: item.title,
            soundtrack: item.soundtrack.soundtrack || item.title,
            ...item.soundtrack,
        }))
        .sort(byOrder)
        .map(({ order, ...soundtrack }) => soundtrack)
}
